def function(text, name):
    match = re.search(r"(?:static\s+)?(?:inline\s+)?(?:uint|uint32_t)\s+" + name + r"\s*\([^;]+?\)\s*\{", text)
    assert match, name
    end = text.index("{", match.start()) + 1
    depth = 1
    while depth:
        depth += (text[end] == "{") - (text[end] == "}")
        end += 1
    return text[match.start():end]


